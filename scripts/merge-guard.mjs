#!/usr/bin/env node
/**
 * 把腾讯渠道防护层移植进抄写版。
 *
 * 抄写版目前只到"假后端"这一层（`src/mock/pack.mjs`），防护层原本长在
 * `pack.js` 里（真渠道包的后端）。这一步做的事：
 *
 *   1. 从 `main_repai/our-free-model-codearts/tencent-gate-guard.js` 取防护层源码
 *      —— 那是从生效中的 pack.js 抽出来的，与安装文件同源；
 *   2. 剥掉它对外部模块作用域的依赖（`readFileSync`/`homedir`/`join`），
 *      改成运行时注入，使它不依赖宿主；
 *   3. 输出到 `src/guard/tencent-gate.js`，逐字节保留规则表与判定逻辑。
 *
 * 只有一处"改写"是必须的：用户规则文件读取。原文直接调用宿主作用域里的
 * `readFileSync`/`homedir`/`join`，在没有 Node fs 的环境（浏览器、测试）里会
 * 直接抛错——而防护层抛错会让整个请求失败，比不防护更糟。改成
 * `env.readFileSync?.(...)` 后，缺 fs 只是"没有用户规则"，内置规则照常生效。
 *
 *   node scripts/merge-guard.mjs
 *   node scripts/merge-guard.mjs --check
 */

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const WORKSPACE = resolve(ROOT, '..')

/**
 * 防护层的源。
 *
 * 优先级：环境变量 → **仓库内基线**（vendor/upstream/）→ 工作区里的原始抽取件。
 *
 * 仓库内基线是必须的：只看 `main_repai/` 那份的话，这个仓库一旦被别人克隆、
 * 或者 `main_repai/` 被清理，`merge-guard` 就跑不了，"防护层有没有被改过"
 * 也就无从复核。基线随仓库走，`src/guard/provenance.json` 里记着它的 sha256。
 */
const VENDORED = join(ROOT, 'vendor/upstream/tencent-gate-guard.js')
const UPSTREAM = join(WORKSPACE, 'main_repai/our-free-model-codearts/tencent-gate-guard.js')

const SOURCE = process.env.OFM_GUARD_SOURCE
  ?? (existsSync(VENDORED) ? VENDORED : UPSTREAM)
const CHECK = process.argv.includes('--check')

if (!existsSync(SOURCE)) {
  console.error(`merge-guard: 找不到防护层源码: ${SOURCE}`)
  console.error('仓库里应有 vendor/upstream/tencent-gate-guard.js；也可以设 OFM_GUARD_SOURCE=<path>。')
  process.exit(2)
}

const raw = readFileSync(SOURCE, 'utf8')
const sourceSha = createHash('sha256').update(raw, 'utf8').digest('hex')

/* ── 找出生效配置函数，确认它依赖哪三个宿主名 ───────────────────────────── */

const CONFIG_FN = 'function tencentGateUserConfig() {'
const configIndex = raw.indexOf(CONFIG_FN)
if (configIndex === -1) {
  console.error('merge-guard: 找不到 tencentGateUserConfig()，防护层结构可能已变，拒绝盲目改写')
  process.exit(2)
}

/**
 * 原函数体里用到 `readFileSync` / `homedir` / `join`（pack.js 顶部从 node:fs、
 * node:os、node:path 导入的同一模块作用域名字）。
 *
 * 移植时不改写函数体 —— 改写函数体就是我在第一版里犯的错：我自作主张重写了
 * 规则过滤条件（原文只要求 `find`/`replace` 是字符串、level 缺省 2，我却改成
 * 必须 1..3 整数），还引入了没定义的 `join`，异常又被原文的 catch 吞掉，
 * 结果「用户扩展规则永远读不到」且没有任何报错。
 *
 * 正确做法：**正文逐字节保留**，只在它前面声明这三个名字（默认是「没有 fs」），
 * 由 bindTencentGateEnv() 覆盖。没有 fs 时原文自己的 catch 会退回内置表，
 * 这正是它在浏览器/无 Node 宿主下应有的行为。
 */
function assertUsesHostNames() {
  const blockEnd = raw.indexOf('\n}', configIndex)
  const body = raw.slice(configIndex, blockEnd)
  for (const name of ['readFileSync', 'homedir', 'join']) {
    if (!new RegExp(`\\b${name}\\(`).test(body)) {
      console.error(`merge-guard: ${CONFIG_FN} 里没有用到 ${name}()，源码结构已变`)
      process.exit(2)
    }
  }
}
assertUsesHostNames()

/**
 * 从第一处顶层声明开始整段保留（规则表、路径遮罩、判定、埋点全在里面）。
 * 注意不能从 tencentGateUserConfig 处切 —— 那会把前面的规则表和路径逻辑丢掉。
 */
const firstDecl = raw.indexOf('var TG_ZW')
if (firstDecl === -1) {
  console.error('merge-guard: 找不到 var TG_ZW，源码结构异常')
  process.exit(2)
}
let body = raw.slice(firstDecl)

/* ── 生成模块 ───────────────────────────────────────────────────────────── */

const header = `/* AUTO-GENERATED by scripts/merge-guard.mjs — 腾讯渠道防护层移植版。
 *
 * Source: main_repai/our-free-model-codearts/tencent-gate-guard.js
 * Source sha256: ${sourceSha}
 * Source bytes: ${raw.length}
 * 重新生成: node scripts/merge-guard.mjs
 *
 * 这份代码原样来自生效中的插件 pack.js（v2.5.4，install sha256 9b6d430a…）。
 *
 * 与原文相比的差异只有「注入」两处，函数体一个字节都没改：
 *   1. 原文靠 pack.js 顶部的 node:fs / node:os / node:path 导入拿到
 *      readFileSync / homedir / join；这里改成模块级的可变绑定，默认未绑定。
 *   2. bindTencentGateEnv() 用来在 Node 里装上真实的三个函数。
 *
 * 为什么不做「就地改写函数体」：第一版那样干过，改坏了 —— 重写了规则过滤条件
 * 还引用了未定义的 join，异常被原文的 catch 吞掉，用户扩展规则永远静默失效。
 * 现在函数体逐字保留，未绑定 fs 时由原文自己的 catch 退回内置规则表，
 * 行为与它在浏览器/无 Node 宿主下应有的一致。
 */

/* 原文从 pack.js 顶部导入的宿主名字。未绑定时为 undefined，
 * tencentGateUserConfig() 的 try/catch 会退回内置规则（这是原文的行为）。 */
let readFileSync;
let homedir;
let join;

/** 装上宿主能力（Node 环境下调用）。只影响「用户扩展规则」，内置规则不受影响。 */
export function bindTencentGateEnv(env) {
  readFileSync = env?.readFileSync;
  homedir = env?.homedir;
  join = env?.join ?? (env?.homedir === undefined ? undefined : ((...parts) => parts.join('/')));
  // 缓存的是「有没有用户规则」，环境变了必须重读
  TG_USER_RULES_CACHE = null;
}

`

/** 原文结尾是给审查看的抽取说明（TOOL_RESULT_IMAGE_TEXT 之后），截掉。 */
const tailMarker = 'var TOOL_RESULT_IMAGE_TEXT'
const tailIndex = body.indexOf(tailMarker)
if (tailIndex !== -1) body = body.slice(0, tailIndex).trimEnd() + '\n'

/** 导出面：调用方需要的那几个，以及便于测试内部判定的。 */
const exports = `
/* ── 导出 ─────────────────────────────────────────────────────────────── */

export {
  TENCENT_GATE_RULES,
  TENCENT_GATE_MAX_ESCALATIONS,
  TG_ZW,
  TG_WS,
  TG_BRAND,
  TG_BRAND_LOOSE,
  TG_PATH_START_RE,
  TG_PATH_QUOTES,
  tencentGateUserConfig,
  tencentGateRules,
  tencentBaseGuardLevel,
  tencentNextGuardLevel,
  tencentCanonicalizeText,
  tencentGateApplyRules,
  tencentGateStats,
  scrubTencentFingerprintMessage,
  applyTencentGateGuard,
  scrubTencentContentFingerprintsInPlace,
  isTencentGateBlock,
  markTencentGateError,
  tencentGateErrorBody,
  isTencentGateBlockError,
  tgTrace,
  tgPathSpans,
  tgMaskPaths,
  tgUnmaskPaths,
  tgRewriteText,
}
`

const output = header + body + exports

const outDir = join(ROOT, 'src', 'guard')
mkdirSync(outDir, { recursive: true })
const path = join(outDir, 'tencent-gate.js')
const previous = existsSync(path) ? readFileSync(path, 'utf8') : null

/**
 * 移植记录。
 *
 * `rewrites` 只有一条，而且是**绑定**而不是改写：函数体逐字节来自源文件。
 * 上一版这里记的是「改写了 tencentGateUserConfig」——那次改写引入了一个
 * 未定义的 `join`，异常又被原文的 catch 吞掉，用户扩展规则静默失效。
 * 这份记录存在的意义就是让「到底动了什么」可核对。
 */
const provenance = {
  // 记录**实际用到的**那份源：仓库内基线时写相对路径，便于在别处复核
  source: SOURCE === VENDORED ? 'vendor/upstream/tencent-gate-guard.js' : 'main_repai/our-free-model-codearts/tencent-gate-guard.js',
  upstreamOrigin: 'dsh-our-free-model@2.5.4 vendor/channel-pack/pack.js（抽取件）',
  sourceSha256: sourceSha,
  sourceBytes: raw.length,
  mergedBytes: output.length,
  mergedSha256: createHash('sha256').update(output, 'utf8').digest('hex'),
  packageVersion: '2.5.4',
  installPackSha256: '9b6d430a51bd047534bba4608024a5e571e277fa8b9534cb143f0db119b544cc',
  rules: 10,
  defaultMaxEscalations: 2,
  rewrites: [
    {
      what: 'readFileSync / homedir / join 三个宿主名字改为模块级可变绑定',
      why: '原文靠 pack.js 顶部的 node:fs / node:os / node:path 导入；移植后需要由宿主注入，否则无 fs 环境会抛错（原文的 catch 会退回内置表，行为不变）',
      bodyUnchanged: true,
    },
  ],
}

const provenancePath = join(outDir, 'provenance.json')
const provenanceText = JSON.stringify(provenance, null, 2) + '\n'
const previousProvenance = existsSync(provenancePath) ? readFileSync(provenancePath, 'utf8') : null

if (previous === output) {
  console.log(`merge-guard: ${'src/guard/tencent-gate.js'} 已是最新`)
} else if (CHECK) {
  console.error('merge-guard --check: src/guard/tencent-gate.js 与源防护层不一致')
  process.exit(1)
} else {
  writeFileSync(path, output)
  console.log(`merge-guard: 写入 src/guard/tencent-gate.js (${output.length} chars)`)
}

if (previousProvenance !== provenanceText) {
  if (CHECK) {
    console.error('merge-guard --check: src/guard/provenance.json 过期')
    process.exit(1)
  }
  writeFileSync(provenancePath, provenanceText)
  console.log('merge-guard: 写入 src/guard/provenance.json')
}

console.log(`merge-guard: 源 sha256 ${sourceSha.slice(0, 16)}…  原文 ${raw.length} 字节`)
console.log('merge-guard: 函数体逐字节保留，仅 3 个宿主名字改为可绑定')
